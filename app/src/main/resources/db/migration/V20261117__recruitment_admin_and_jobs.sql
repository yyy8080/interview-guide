-- 招聘改造 P0：HR 后台账号 + 招聘岗位

CREATE TABLE IF NOT EXISTS admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  display_name VARCHAR(64),
  email VARCHAR(255),
  role VARCHAR(20) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  token_version INTEGER NOT NULL DEFAULT 0,
  last_login_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_admin_users_username UNIQUE (username),
  CONSTRAINT admin_users_role_check CHECK (role IN ('ADMIN', 'HR', 'INTERVIEWER'))
);

COMMENT ON TABLE admin_users IS 'HR 后台账号';
COMMENT ON COLUMN admin_users.token_version IS 'JWT 版本号，修改密码/禁用时递增以吊销已签发令牌';

CREATE TABLE IF NOT EXISTS job_positions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(128) NOT NULL,
  department VARCHAR(128),
  location VARCHAR(128),
  employment_type VARCHAR(20) NOT NULL DEFAULT 'FULL_TIME',
  headcount INTEGER,
  salary_range VARCHAR(64),
  jd_text TEXT NOT NULL,
  categories_json TEXT,
  skill_id VARCHAR(64) NOT NULL,
  difficulty VARCHAR(16) NOT NULL,
  question_count INTEGER NOT NULL,
  interview_mode VARCHAR(16) NOT NULL,
  knowledge_base_id BIGINT,
  time_limit_minutes INTEGER,
  screening_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  screening_threshold INTEGER,
  ai_pass_threshold INTEGER NOT NULL,
  llm_provider VARCHAR(50),
  status VARCHAR(16) NOT NULL,
  deadline TIMESTAMP(6),
  published_at TIMESTAMP(6),
  created_by BIGINT,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT job_positions_status_check CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED')),
  CONSTRAINT job_positions_interview_mode_check CHECK (interview_mode IN ('TEXT', 'VOICE', 'BOTH')),
  CONSTRAINT job_positions_employment_type_check
    CHECK (employment_type IN ('FULL_TIME', 'PART_TIME', 'INTERN', 'CONTRACT')),
  CONSTRAINT fk_job_positions_created_by FOREIGN KEY (created_by) REFERENCES admin_users(id)
);

CREATE INDEX IF NOT EXISTS idx_job_positions_status_updated ON job_positions (status, updated_at);

COMMENT ON TABLE job_positions IS '招聘岗位';
COMMENT ON COLUMN job_positions.categories_json IS 'JD 解析出的考察维度（InterviewSkillService.CategoryDTO 列表）';
COMMENT ON COLUMN job_positions.skill_id IS '面试主题：预设 skill 或 custom（按 JD 维度出题）';
COMMENT ON COLUMN job_positions.interview_mode IS '在线面试形式：TEXT / VOICE / BOTH（候选人自选）';
COMMENT ON COLUMN job_positions.ai_pass_threshold IS 'AI 面试评估通过分数线（0-100）';
COMMENT ON COLUMN job_positions.screening_threshold IS 'AI 简历初筛通过分数线（0-100）';
