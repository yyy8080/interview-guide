-- 在线面试防作弊升级（低打扰方案）：
-- 1. 行为事件记录离开时长、所在题号、字数；新增分屏 / 扩展屏 / 语音改写 / 语音应答延迟事件
-- 2. 新增逐题作答遥测（耗时、首次输入延迟、键入 / 粘贴字数、输入突增、作答期间离开时长）
-- 3. 投递记录保存作弊风险分与等级，供 HR 列表展示与筛选
-- 4. 岗位级开关：离开提醒、轻量水印

ALTER TABLE interview_proctor_events ADD COLUMN IF NOT EXISTS duration_ms BIGINT;
ALTER TABLE interview_proctor_events ADD COLUMN IF NOT EXISTS question_index INT;
ALTER TABLE interview_proctor_events ADD COLUMN IF NOT EXISTS chars INT;

ALTER TABLE interview_proctor_events DROP CONSTRAINT IF EXISTS interview_proctor_events_type_check;
ALTER TABLE interview_proctor_events ADD CONSTRAINT interview_proctor_events_type_check
  CHECK (event_type IN ('TAB_HIDDEN', 'WINDOW_BLUR', 'PASTE', 'COPY', 'FULLSCREEN_EXIT',
                        'VIEWPORT_SHRINK', 'MULTI_SCREEN', 'VOICE_TEXT_EDITED', 'VOICE_SLOW_RESPONSE'));

COMMENT ON COLUMN interview_proctor_events.duration_ms IS '离开页面 / 失焦持续时长（毫秒），语音应答延迟（毫秒）';
COMMENT ON COLUMN interview_proctor_events.question_index IS '事件发生时正在作答的题目序号（从 0 开始）';
COMMENT ON COLUMN interview_proctor_events.chars IS '粘贴字数 / 语音改写字数';

CREATE TABLE IF NOT EXISTS interview_answer_telemetry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL,
  question_index INT NOT NULL,
  duration_ms BIGINT,
  first_input_ms BIGINT,
  typed_chars INT,
  pasted_chars INT,
  max_burst_chars INT,
  away_ms BIGINT,
  answer_chars INT,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_answer_telemetry_application FOREIGN KEY (application_id) REFERENCES applications(id) ON DELETE CASCADE,
  CONSTRAINT uk_answer_telemetry_question UNIQUE (application_id, question_index)
);

COMMENT ON TABLE interview_answer_telemetry IS '文字面试逐题作答遥测（无感采集），用于作弊风险评分与 HR 复核';

ALTER TABLE applications ADD COLUMN IF NOT EXISTS proctor_risk_score INT;
ALTER TABLE applications ADD COLUMN IF NOT EXISTS proctor_risk_level VARCHAR(16);
ALTER TABLE applications DROP CONSTRAINT IF EXISTS ck_applications_proctor_risk_level;
ALTER TABLE applications ADD CONSTRAINT ck_applications_proctor_risk_level
  CHECK (proctor_risk_level IS NULL OR proctor_risk_level IN ('LOW', 'MEDIUM', 'HIGH'));
CREATE INDEX IF NOT EXISTS idx_applications_proctor_risk ON applications (proctor_risk_level);

COMMENT ON COLUMN applications.proctor_risk_score IS '在线面试作弊风险分 0-100（交卷时计算，仅供参考，不自动淘汰）';
COMMENT ON COLUMN applications.proctor_risk_level IS '作弊风险等级：LOW / MEDIUM / HIGH';

ALTER TABLE job_positions ADD COLUMN IF NOT EXISTS proctor_away_reminder BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE job_positions ADD COLUMN IF NOT EXISTS proctor_watermark BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN job_positions.proctor_away_reminder IS '候选人长时间离开页面后回来时是否给出柔和提醒';
COMMENT ON COLUMN job_positions.proctor_watermark IS '在线面试页面是否显示极淡的候选人信息水印';
