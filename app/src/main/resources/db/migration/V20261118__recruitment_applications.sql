-- 招聘改造 P1-P4：候选人、投递单、状态审计、防作弊事件；简历去重调整

-- 简历不再全局去重：不同候选人 / 不同岗位可能上传同一份文件
ALTER TABLE resumes DROP CONSTRAINT IF EXISTS idx_resume_hash;
CREATE INDEX IF NOT EXISTS idx_resumes_file_hash ON resumes (file_hash);

CREATE TABLE IF NOT EXISTS candidates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  name VARCHAR(64),
  phone VARCHAR(32),
  last_login_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_candidates_email UNIQUE (email)
);

COMMENT ON TABLE candidates IS '候选人（免注册，邮箱验证码即身份凭证）';

CREATE TABLE IF NOT EXISTS applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT NOT NULL,
  candidate_id BIGINT NOT NULL,
  resume_id BIGINT NOT NULL,
  candidate_name VARCHAR(64) NOT NULL,
  candidate_phone VARCHAR(32),
  status VARCHAR(32) NOT NULL,
  interview_mode VARCHAR(16),
  interview_session_id VARCHAR(64),
  voice_session_id BIGINT,
  screening_score INTEGER,
  screening_result_json TEXT,
  ai_score INTEGER,
  ai_decision VARCHAR(16),
  ai_result_json TEXT,
  task_attempt_id VARCHAR(64),
  task_updated_at TIMESTAMP(6),
  task_retry_count INTEGER NOT NULL DEFAULT 0,
  task_error VARCHAR(500),
  hr_reviewer_id BIGINT,
  hr_comment TEXT,
  hr_reviewed_at TIMESTAMP(6),
  consent_at TIMESTAMP(6) NOT NULL,
  submitted_at TIMESTAMP(6) NOT NULL,
  invited_at TIMESTAMP(6),
  invite_expires_at TIMESTAMP(6),
  interview_started_at TIMESTAMP(6),
  interview_deadline_at TIMESTAMP(6),
  interview_completed_at TIMESTAMP(6),
  decided_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uk_applications_job_candidate UNIQUE (job_id, candidate_id),
  CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES job_positions(id),
  CONSTRAINT fk_applications_candidate FOREIGN KEY (candidate_id) REFERENCES candidates(id),
  CONSTRAINT fk_applications_resume FOREIGN KEY (resume_id) REFERENCES resumes(id),
  CONSTRAINT fk_applications_hr_reviewer FOREIGN KEY (hr_reviewer_id) REFERENCES admin_users(id),
  CONSTRAINT applications_status_check CHECK (status IN (
    'SUBMITTED', 'SCREENING', 'SCREEN_REJECTED', 'INTERVIEW_INVITED', 'INTERVIEWING',
    'AI_REVIEWING', 'AI_PASSED', 'AI_REJECTED', 'HR_APPROVED', 'HR_REJECTED',
    'OFFLINE_SCHEDULED', 'OFFLINE_CONFIRMED', 'EXPIRED')),
  CONSTRAINT applications_interview_mode_check CHECK (interview_mode IS NULL OR interview_mode IN ('TEXT', 'VOICE')),
  CONSTRAINT applications_ai_decision_check CHECK (ai_decision IS NULL OR ai_decision IN ('PASS', 'REJECT'))
);

CREATE INDEX IF NOT EXISTS idx_applications_job_status ON applications (job_id, status);
CREATE INDEX IF NOT EXISTS idx_applications_status_updated ON applications (status, updated_at);
CREATE INDEX IF NOT EXISTS idx_applications_candidate ON applications (candidate_id);
CREATE INDEX IF NOT EXISTS idx_applications_interview_session ON applications (interview_session_id);
CREATE INDEX IF NOT EXISTS idx_applications_voice_session ON applications (voice_session_id);
CREATE INDEX IF NOT EXISTS idx_applications_resume ON applications (resume_id);

COMMENT ON TABLE applications IS '投递单：串联简历、AI 初筛、在线面试、AI 决策、HR 审核与线下面试';
COMMENT ON COLUMN applications.task_attempt_id IS '异步任务（初筛 / AI 决策）执行代次，防止超时回收后旧消费者落库';

CREATE TABLE IF NOT EXISTS application_status_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL,
  from_status VARCHAR(32),
  to_status VARCHAR(32) NOT NULL,
  operator_type VARCHAR(16) NOT NULL,
  operator_id BIGINT,
  remark VARCHAR(1000),
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_application_status_logs_application FOREIGN KEY (application_id) REFERENCES applications(id) ON DELETE CASCADE,
  CONSTRAINT application_status_logs_operator_check CHECK (operator_type IN ('SYSTEM', 'AI', 'HR', 'CANDIDATE'))
);

CREATE INDEX IF NOT EXISTS idx_application_status_logs_app ON application_status_logs (application_id, created_at);

CREATE TABLE IF NOT EXISTS interview_proctor_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL,
  event_type VARCHAR(32) NOT NULL,
  detail VARCHAR(500),
  occurred_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_proctor_events_application FOREIGN KEY (application_id) REFERENCES applications(id) ON DELETE CASCADE,
  CONSTRAINT interview_proctor_events_type_check CHECK (event_type IN ('TAB_HIDDEN', 'WINDOW_BLUR', 'PASTE', 'COPY', 'FULLSCREEN_EXIT'))
);

CREATE INDEX IF NOT EXISTS idx_proctor_events_app ON interview_proctor_events (application_id, occurred_at);

COMMENT ON TABLE interview_proctor_events IS '在线面试防作弊事件（切屏、失焦、粘贴等），作为 AI 决策与 HR 审核参考';
