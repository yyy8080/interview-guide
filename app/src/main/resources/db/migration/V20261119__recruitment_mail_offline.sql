-- SMTP 配置（单行，id 固定为 1）
CREATE TABLE IF NOT EXISTS mail_settings (
  id BIGINT PRIMARY KEY,
  enabled BOOLEAN NOT NULL DEFAULT FALSE,
  host VARCHAR(255),
  port INTEGER,
  username VARCHAR(255),
  password_ciphertext TEXT,
  password_nonce VARCHAR(64),
  security VARCHAR(16) NOT NULL DEFAULT 'SSL',
  from_address VARCHAR(255),
  from_name VARCHAR(128),
  company_name VARCHAR(128),
  portal_base_url VARCHAR(512),
  contact_info VARCHAR(512),
  updated_by BIGINT,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT ck_mail_settings_singleton CHECK (id = 1),
  CONSTRAINT ck_mail_settings_security CHECK (security IN ('NONE', 'SSL', 'STARTTLS'))
);

COMMENT ON TABLE mail_settings IS '后台 SMTP 配置（密码 AES-GCM 加密存储）';

-- 邮件模板：未入库的模板使用代码内置默认值
CREATE TABLE IF NOT EXISTS email_templates (
  code VARCHAR(64) PRIMARY KEY,
  subject VARCHAR(255) NOT NULL,
  body TEXT NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  updated_by BIGINT,
  updated_at TIMESTAMP(6) NOT NULL
);

COMMENT ON TABLE email_templates IS '邮件模板（支持 {变量} 占位符）';

-- 邮件发件箱 / 发送日志
CREATE TABLE IF NOT EXISTS email_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT,
  to_address VARCHAR(255) NOT NULL,
  template_code VARCHAR(64) NOT NULL,
  subject VARCHAR(255) NOT NULL,
  body TEXT NOT NULL,
  attachment_ics TEXT,
  status VARCHAR(16) NOT NULL,
  error VARCHAR(500),
  retry_count INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMP(6),
  sent_at TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT ck_email_logs_status CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS idx_email_logs_status_next ON email_logs (status, next_attempt_at);
CREATE INDEX IF NOT EXISTS idx_email_logs_application ON email_logs (application_id);

COMMENT ON TABLE email_logs IS '邮件发件箱：事务内写入 PENDING，提交后异步发送并重试';

