-- 招聘定向邀请制（P10）：后台直接输入候选人邮箱发送邀请邮件，仅受邀邮箱可投递简历与进入面试，实时跟踪参面状态

CREATE TABLE IF NOT EXISTS recruitment_invitations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT NOT NULL,
  email VARCHAR(255) NOT NULL,
  candidate_name VARCHAR(64),
  invite_code VARCHAR(64) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  skip_screening BOOLEAN NOT NULL DEFAULT FALSE,
  note VARCHAR(500),
  invited_by BIGINT,
  invited_at TIMESTAMP(6) NOT NULL,
  expires_at TIMESTAMP(6),
  revoked_at TIMESTAMP(6),
  application_id BIGINT,
  last_email_log_id BIGINT,
  send_count INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT ck_recruitment_invitations_status CHECK (status IN ('ACTIVE', 'REVOKED')),
  CONSTRAINT uk_recruitment_invitations_code UNIQUE (invite_code),
  CONSTRAINT uk_recruitment_invitations_job_email UNIQUE (job_id, email)
);

CREATE INDEX IF NOT EXISTS idx_recruitment_invitations_email ON recruitment_invitations (email);
CREATE INDEX IF NOT EXISTS idx_recruitment_invitations_job_status ON recruitment_invitations (job_id, status);
CREATE INDEX IF NOT EXISTS idx_recruitment_invitations_application ON recruitment_invitations (application_id);

COMMENT ON TABLE recruitment_invitations IS '招聘面试定向邀请表：控制受邀邮箱投递与面试准入，并跟踪候选人是否参加面试';
