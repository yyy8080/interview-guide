-- 在线笔试（选择题 / 填空题）：
-- 1. 岗位级配置：是否启用笔试、各题型数量、笔试时长、笔试成绩在综合分中的权重
-- 2. 每个投递一份笔试（AI 按岗位 JD 为每位候选人实时生成），保存题目、作答与判分结果
-- 3. 投递记录保存笔试分，供 HR 列表展示

ALTER TABLE job_positions ADD COLUMN IF NOT EXISTS written_test_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE job_positions ADD COLUMN IF NOT EXISTS written_single_count INT NOT NULL DEFAULT 5;
ALTER TABLE job_positions ADD COLUMN IF NOT EXISTS written_multi_count INT NOT NULL DEFAULT 3;
ALTER TABLE job_positions ADD COLUMN IF NOT EXISTS written_fill_count INT NOT NULL DEFAULT 2;
ALTER TABLE job_positions ADD COLUMN IF NOT EXISTS written_time_limit_minutes INT NOT NULL DEFAULT 15;
ALTER TABLE job_positions ADD COLUMN IF NOT EXISTS written_weight INT NOT NULL DEFAULT 30;

ALTER TABLE job_positions DROP CONSTRAINT IF EXISTS ck_job_positions_written_config;
ALTER TABLE job_positions ADD CONSTRAINT ck_job_positions_written_config CHECK (
  written_single_count BETWEEN 0 AND 20
  AND written_multi_count BETWEEN 0 AND 20
  AND written_fill_count BETWEEN 0 AND 20
  AND written_time_limit_minutes BETWEEN 5 AND 120
  AND written_weight BETWEEN 0 AND 100
);

COMMENT ON COLUMN job_positions.written_test_enabled IS '是否在 AI 面试前进行在线笔试（选择题 / 填空题）';
COMMENT ON COLUMN job_positions.written_single_count IS '笔试单选题数量';
COMMENT ON COLUMN job_positions.written_multi_count IS '笔试多选题数量';
COMMENT ON COLUMN job_positions.written_fill_count IS '笔试填空题数量';
COMMENT ON COLUMN job_positions.written_time_limit_minutes IS '笔试时长（分钟）';
COMMENT ON COLUMN job_positions.written_weight IS '笔试成绩在综合分中的权重（0-100，%）';

CREATE TABLE IF NOT EXISTS written_tests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL,
  status VARCHAR(16) NOT NULL,
  questions_json TEXT NOT NULL,
  answers_json TEXT,
  results_json TEXT,
  score INT,
  correct_count INT,
  total_count INT NOT NULL,
  started_at TIMESTAMP(6) NOT NULL,
  deadline_at TIMESTAMP(6) NOT NULL,
  submitted_at TIMESTAMP(6),
  graded_at TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_written_tests_application FOREIGN KEY (application_id) REFERENCES applications(id) ON DELETE CASCADE,
  CONSTRAINT uk_written_tests_application UNIQUE (application_id),
  CONSTRAINT ck_written_tests_status CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'GRADED')),
  CONSTRAINT ck_written_tests_score CHECK (score IS NULL OR score BETWEEN 0 AND 100)
);

CREATE INDEX IF NOT EXISTS idx_written_tests_status_deadline ON written_tests (status, deadline_at);

COMMENT ON TABLE written_tests IS '候选人在线笔试：AI 实时生成的选择题 / 填空题、作答与自动判分结果';
COMMENT ON COLUMN written_tests.questions_json IS '题目（含标准答案，仅后台可见）';
COMMENT ON COLUMN written_tests.answers_json IS '候选人作答：题号 -> 选项 / 填空内容';
COMMENT ON COLUMN written_tests.results_json IS '逐题判分结果（规则判定 / AI 语义判定）';

ALTER TABLE applications ADD COLUMN IF NOT EXISTS written_score INT;
COMMENT ON COLUMN applications.written_score IS '在线笔试得分 0-100';
